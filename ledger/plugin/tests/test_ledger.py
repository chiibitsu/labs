"""Tests for the Time Dividend ledger client. Every transcript here is synthetic.

Run:  python3 -I ledger/plugin/tests/test_ledger.py
Nothing here reaches the live ledger: writes go to a dry-run file or to a closed local port.
"""
import importlib.util, json, os, subprocess, sys, tempfile, unittest
from datetime import datetime, timedelta, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
CLIENT = os.path.join(HERE, "..", "scripts", "ledger.py")
T0 = datetime(2026, 1, 1, tzinfo=timezone.utc)


def iso(sec):
    return (T0 + timedelta(seconds=sec)).isoformat().replace("+00:00", "Z")


def user(sec, content, **kw):
    return {"type": "user", "uuid": f"u{sec}", "timestamp": iso(sec), "message": {"role": "user", "content": content}, **kw}


def asst(sec, **kw):
    return {"type": "assistant", "uuid": f"a{sec}", "timestamp": iso(sec),
            "message": {"role": "assistant", "content": [{"type": "text", "text": "ok"}]}, **kw}


def cost(until_sec, usd=1.25, with_times=True):
    d = {"type": "cost-state", "sessionId": "x", "totalCostUSD": usd,
         "modelUsage": {"model-a": {"inputTokens": 100, "cacheCreationInputTokens": 20,
                                    "cacheReadInputTokens": 3000, "outputTokens": 400}}}
    if with_times:
        d.update({"startTime": T0.timestamp() * 1000, "totalDuration": until_sec * 1000})
    return d


# Her two prompts at 0 s and 400 s. Everything else is the AI, a tool, or Claude Code itself.
BASE = [
    user(0, "Build the thing"),
    asst(10),
    user(70, [{"type": "tool_result", "tool_use_id": "t1", "content": "done"}]),
    asst(130),
    user(150, [{"type": "text", "text": "[Request interrupted by user for tool use]"}]),
    user(400, [{"type": "text", "text": "Now the second part"}]),
    asst(420),
    user(460, "This session is being continued from a previous conversation that ran out of context.",
         isCompactSummary=True),
    user(500, "<task-notification>done</task-notification>", origin={"kind": "task-notification"}),
    asst(520),
    asst(530, isSidechain=True),
]
# AI events 10,70,130,150,420,460,500,520: gaps 60+60+20+270+40+40+20 = 510 s = 8.5 min.
# Her time: 120 (first prompt) + min(400-150, 300) = 250 + 120 (final read) = 490 s = 8.2 min.


def load_client(home):
    os.environ["HOME"] = home
    spec = importlib.util.spec_from_file_location("ledger_under_test", CLIENT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def rows_in(path):
    with open(path) as f:
        return [json.loads(l) for l in f]


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        for d in lines:
            f.write((d if isinstance(d, str) else json.dumps(d)) + "\n")


class Measure(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.L = load_client(self.tmp)
        self.path = os.path.join(self.tmp, "t.jsonl")

    def test_times_and_cost(self):
        write(self.path, BASE + [cost(520)])
        m = self.L.measure(self.path)
        self.assertEqual(m["ai_minutes"], 8.5)
        self.assertEqual(m["you_minutes"], 8.2)
        self.assertEqual(m["started_at"], iso(0).replace("Z", "+00:00"))
        self.assertEqual(m["ended_at"], iso(520).replace("Z", "+00:00"))
        self.assertEqual(m["first_prompt"], "Build the thing")
        self.assertEqual(m["cost_usd"], 1.25)
        self.assertEqual((m["tokens_input"], m["tokens_cache_read"], m["tokens_output"]), (120, 3000, 400))
        self.assertEqual(m["cost_basis"], "reported")

    def test_synthetic_texts_are_not_her_prompts(self):
        L = self.L
        for text in ["[Request interrupted by user]", "[Request interrupted by user for tool use]",
                     "[Tool use interrupted]", "Caveat: The messages below were generated by the user while running local commands.",
                     "<command-name>/clear</command-name>", "[SYSTEM NOTIFICATION - NOT USER INPUT] x"]:
            self.assertFalse(L.is_human_prompt(user(1, text)), text)
            self.assertFalse(L.is_human_prompt(user(1, [{"type": "text", "text": text}])), text)
            self.assertFalse(L.is_human_prompt(user(1, text, origin={"kind": "human"})), text)
        self.assertFalse(L.is_human_prompt(user(1, "summary", isCompactSummary=True)))
        self.assertFalse(L.is_human_prompt(user(1, "hi", isMeta=True)))
        self.assertTrue(L.is_human_prompt(user(1, "fix the header")))
        self.assertTrue(L.is_human_prompt(user(1, [{"type": "image", "source": {}}])))

    def test_title_skips_an_interrupt_that_comes_first(self):
        write(self.path, [user(0, [{"type": "text", "text": "[Request interrupted by user]"}]), asst(5),
                          user(20, "the real ask"), asst(30)])
        self.assertEqual(self.L.measure(self.path)["first_prompt"], "the real ask")

    def test_no_cost_record_means_no_cost(self):
        write(self.path, BASE)
        m = self.L.measure(self.path)
        for k in ("cost_usd", "cost_basis", "tokens_input"):
            self.assertNotIn(k, m)

    def test_cost_that_stops_early_is_partial(self):
        write(self.path, BASE + [cost(520), asst(900), asst(1300)])
        m = self.L.measure(self.path)
        self.assertEqual(m["cost_basis"], "partial")
        self.assertEqual(m["cost_usd"], 1.25)

    def test_cost_without_times_uses_last_event_before_it(self):
        write(self.path, BASE + [cost(0, with_times=False), asst(900), asst(1300)])
        self.assertEqual(self.L.measure(self.path)["cost_basis"], "partial")
        write(self.path, BASE + [cost(0, with_times=False)])
        self.assertEqual(self.L.measure(self.path)["cost_basis"], "reported")

    def test_no_prompt_of_hers_leaves_her_minutes_unknown(self):
        write(self.path, [asst(0), asst(30), user(40, "<task-notification/>", origin={"kind": "task-notification"})])
        m = self.L.measure(self.path)
        self.assertIsNone(m["you_minutes"])
        self.assertEqual(m["ai_minutes"], 0.7)

    def test_a_bad_line_costs_nothing(self):
        write(self.path, ["{not json", "[]"] + BASE + [cost(520)])
        self.assertEqual(self.L.measure(self.path)["ai_minutes"], 8.5)


def run_hook(env, event, sid, cwd, transcript=None):
    data = {"hook_event_name": event, "session_id": sid, "cwd": cwd}
    if transcript:
        data["transcript_path"] = transcript
    p = subprocess.run([sys.executable, "-I", CLIENT, "hook"], input=json.dumps(data), env=env,
                       capture_output=True, text=True, timeout=30)
    assert p.returncode == 0, p.stderr
    return p.stdout.strip()


class Hooks(unittest.TestCase):
    def setUp(self):
        self.home = tempfile.mkdtemp()
        self.state = os.path.join(self.home, "state")
        os.makedirs(self.state)
        self.cwd = os.path.join(self.home, "repo")
        os.makedirs(self.cwd)
        self.env = {"HOME": self.home, "PATH": os.environ.get("PATH", ""), "LEDGER_STATE_DIR": self.state,
                    # a closed local port: any write that escapes dry-run fails here, never reaches the ledger
                    "LEDGER_URL": "http://127.0.0.1:9", "LEDGER_TOKEN": "test-token-not-real"}

    def transcript(self, sid, lines):
        p = os.path.join(self.home, ".claude", "projects", "-repo", sid + ".jsonl")
        write(p, lines)
        return p

    def test_not_wired_is_said_once(self):
        env = dict(self.env)
        env.pop("LEDGER_TOKEN")
        first = json.loads(run_hook(env, "UserPromptSubmit", "s1", self.cwd))
        self.assertIn("NOT wired", first["hookSpecificOutput"]["additionalContext"])
        self.assertEqual(run_hook(env, "UserPromptSubmit", "s1", self.cwd), "")
        self.assertEqual(run_hook(env, "Stop", "s1", self.cwd), "")

    def test_stop_records_the_session(self):
        open(os.path.join(self.state, "dry-run"), "w").close()
        t = self.transcript("s1", BASE + [cost(520)])
        self.assertEqual(run_hook(self.env, "Stop", "s1", self.cwd, t), "")
        rows = rows_in(os.path.join(self.state, "dry-run.jsonl"))
        self.assertEqual(len(rows), 1)
        self.assertNotIn("p_token", rows[0])
        e = rows[0]["p_entry"]
        self.assertEqual((e["external_id"], e["ai_minutes"], e["you_minutes"], e["cost_usd"], e["cost_basis"]),
                         ("s1", 8.5, 8.2, 1.25, "reported"))
        self.assertEqual(e["title_if_empty"], "Build the thing")
        self.assertEqual(e["project"], "repo")

    def test_failed_write_is_said_once_to_her_and_once_to_the_session(self):
        t = self.transcript("s1", BASE)
        out = json.loads(run_hook(self.env, "Stop", "s1", self.cwd, t))
        self.assertIn("not recorded", out["systemMessage"])
        self.assertEqual(run_hook(self.env, "Stop", "s1", self.cwd, t), "")  # same failure: said already
        ctx = json.loads(run_hook(self.env, "UserPromptSubmit", "s1", self.cwd))["hookSpecificOutput"]["additionalContext"]
        self.assertIn("last automatic write for this session failed", ctx)
        ctx2 = run_hook(self.env, "UserPromptSubmit", "s1", self.cwd)
        self.assertNotIn("failed", ctx2)

    def test_subagent_transcripts_never_log(self):
        open(os.path.join(self.state, "dry-run"), "w").close()
        p = os.path.join(self.home, ".claude", "projects", "-repo", "s1", "subagents", "agent-1.jsonl")
        write(p, BASE)
        self.assertEqual(run_hook(self.env, "Stop", "s1", self.cwd, p), "")
        self.assertFalse(os.path.exists(os.path.join(self.state, "dry-run.jsonl")))

    def test_two_sessions_in_one_folder_keep_their_own_state(self):
        open(os.path.join(self.state, "dry-run"), "w").close()
        ta = self.transcript("sa", BASE)
        tb = self.transcript("sb", [user(0, "other session"), asst(60)])
        run_hook(self.env, "Stop", "sa", self.cwd, ta)
        run_hook(self.env, "Stop", "sb", self.cwd, tb)
        rows = [r["p_entry"] for r in rows_in(os.path.join(self.state, "dry-run.jsonl"))]
        self.assertEqual([(r["external_id"], r["title_if_empty"]) for r in rows],
                         [("sa", "Build the thing"), ("sb", "other session")])
        # `entry` without the harness's session id cannot tell them apart, so it names none.
        env = dict(self.env)
        p = subprocess.run([sys.executable, "-I", CLIENT, "entry"], input='{"title": "x"}', env=env, cwd=self.cwd,
                           capture_output=True, text=True, timeout=30)
        self.assertIn("no single recent session", p.stdout)
        rows = [r["p_entry"] for r in rows_in(os.path.join(self.state, "dry-run.jsonl"))]
        self.assertNotIn("external_id", rows[-1])
        # With the harness's id it measures the right one.
        env["CLAUDE_CODE_SESSION_ID"] = "sb"
        subprocess.run([sys.executable, "-I", CLIENT, "entry"], input='{"title": "x"}', env=env, cwd=self.cwd,
                       capture_output=True, text=True, timeout=30)
        last = [r["p_entry"] for r in rows_in(os.path.join(self.state, "dry-run.jsonl"))][-1]
        self.assertEqual((last["external_id"], last["ai_minutes"]), ("sb", 0.0))


if __name__ == "__main__":
    unittest.main(verbosity=2)
